pub fn parse_fp_reg(name: &str) -> Option<u32> {
    if let Some(rest) = name.strip_prefix('f') {
        if !rest.is_empty() && rest.bytes().all(|c| c.is_ascii_digit()) {
            let n: u32 = rest.parse().ok()?;
            if n < 32 {
                return Some(n);
            }
            return None;
        }
    }
    let r = match name {
        "ft0" => 0,
        "ft1" => 1,
        "ft2" => 2,
        "ft3" => 3,
        "ft4" => 4,
        "ft5" => 5,
        "ft6" => 6,
        "ft7" => 7,
        "fs0" => 8,
        "fs1" => 9,
        "fa0" => 10,
        "fa1" => 11,
        "fa2" => 12,
        "fa3" => 13,
        "fa4" => 14,
        "fa5" => 15,
        "fa6" => 16,
        "fa7" => 17,
        "fs2" => 18,
        "fs3" => 19,
        "fs4" => 20,
        "fs5" => 21,
        "fs6" => 22,
        "fs7" => 23,
        "fs8" => 24,
        "fs9" => 25,
        "fs10" => 26,
        "fs11" => 27,
        "ft8" => 28,
        "ft9" => 29,
        "ft10" => 30,
        "ft11" => 31,
        _ => return None,
    };
    Some(r)
}

